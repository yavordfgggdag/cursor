import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const file = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'site/index.html');
let h = readFileSync(file, 'utf8');

// Fix broken em-dash comma artifacts
h = h.replace(/ ,  /g, ', ');
h = h.replace(/ \. Но /g, '. ');

const fixes = [
  ['Структуриран процес', 'Ясен план'],
  ['структурата на четиринайсетте дни', 'редът за 14 дни'],
  ['Погрешната условна връзка', 'Грешната връзка в главата'],
  ['седмични седмични материали', 'седмични материали'],
  ['<!-- ОФЕРТА 1 ,  кратко -->', '<!-- ОФЕРТА 1 кратко -->'],
  ['<!-- ОФЕРТА 2 ,  пълно -->', '<!-- ОФЕРТА 2 пълно -->'],
  ['„Системата Легло и Сън" ,  защо', '„Системата Легло и Сън": защо'],
  ['<span>план за спокойно заспиване за 14 дни ,  само', '<span>План за 14 дни · само'],
  ['<p>план за спокойно заспиване за 14 дни</p>', '<p>План за спокойно заспиване за 14 дни</p>'],
  ['Бонус 1 „Затваряне на деня за 7 дни"', 'Бонус 1 „Затваряне на деня" за 7 дни'],
  ['<p class="product-desc">Ясен план, основан на „Системата Легло и Сън" ,  за да знаеш', '<p class="product-desc">Ясен план, основан на „Системата Легло и Сън", за да знаеш'],
  ['<p class="product-desc">Ясен план, основан на „Системата Легло и Сън" ,  за да спреш', '<p class="product-desc">Ясен план, основан на „Системата Легло и Сън", за да спреш'],
  ['правилната връзка ,  ЛЕГЛО', 'правилната връзка: ЛЕГЛО'],
  ['принципно различен подход ,  не', 'принципно различен подход. Не'],
  ['Въпрос е на правилния ясен план', 'Въпросът е в ясния план'],
  ['въпрос е на правилния', 'въпросът е в'],
];

for (const [a, b] of fixes) h = h.split(a).join(b);

// Conversational subtitle fix
h = h.replace(
  /<p class="subtitle reveal">[\s\S]*?<\/p>/,
  '<p class="subtitle reveal">Ако си стигнал дотук, вече знаеш защо отделните трикове не са помагали. Не липсва воля. Липсва ясен план за трудните вечери.</p>',
);

writeFileSync(file, h);
console.log('Cleaned index.html');
